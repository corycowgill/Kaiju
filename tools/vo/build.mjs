// Commentary build: tools/vo/script/*.txt -> src/wrestling/commentaryLines.js (what the game reads)
//                                          + tools/vo/out/utterances.json (what tts.py voices).
//   node tools/vo/build.mjs
// An utterance's audio file is named by a hash of its speaker and spoken text, so editing a line
// re-voices only that line. Durations come from tools/vo/out/durations.json (written by tts.py):
// a line without one is caption-only in the game.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const KEY = { gorrak: 'godzilla', mechra: 'mecha', tridon: 'ghidorah' };
const SPEAKER = { M: 'mike', V: 'vance' };

/** What the voice model is given for a caption: names it would misread respelled, shouting toned down to sentence case. */
export function spoken(text) {
  let s = text;
  s = s.replace(/\b([A-Z][A-Z'’]+)\b/g, (w) => (w.length > 1 && !/^(OK|TV|II|III)$/.test(w) ? w[0] + w.slice(1).toLowerCase() : w));
  s = s.replace(/\bD\.D\.T\./gi, 'D D T').replace(/\bL tracks?\b/g, 'El tracks').replace(/\bL train\b/g, 'El train');
  s = s.replace(/\bMechra\b/gi, 'Meckra').replace(/\bTridon\b/gi, 'Try-don').replace(/\bGorrak\b/gi, 'Gorrack').replace(/Gor-rak/gi, 'Gor-rack');
  s = s.replace(/\bAon\b/g, 'A-on').replace(/\bShedd\b/g, 'Shed').replace(/\bPritzker\b/g, 'Pritsker');
  return s;
}

function parse(file) {
  const out = [];
  let topic = '', cond = {}, cur = null;
  const flush = () => { if (cur && cur.s.length) out.push(cur); cur = null; };
  for (const raw of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    if (line.startsWith('#')) continue;
    if (!line) { flush(); continue; }
    if (line.startsWith('@')) {
      flush();
      const parts = line.slice(1).trim().split(/\s+/);
      topic = parts.shift(); cond = {};
      for (const p of parts) {
        const i = p.indexOf(':'), k = p.slice(0, i), v = p.slice(i + 1);
        if (k === 'a' || k === 'v') cond[k] = KEY[v] || fail(file, line, 'kaiju ' + v);
        else if (k === 'pair') cond.pair = v.split('+').map((x) => KEY[x] || fail(file, line, 'kaiju ' + x)).sort().join('+');
        else if (['aa', 'va', 'mu', 'lm', 'm'].includes(k)) cond[k] = v;
        else fail(file, line, 'cond ' + k);
      }
      continue;
    }
    const m = /^([MV]):\s*(.+)$/.exec(line);
    if (!m) fail(file, line, 'not a line');
    if (!topic) fail(file, line, 'no topic yet');
    if (!cur) cur = { t: topic, c: cond, s: [] };
    cur.s.push([m[1], m[2]]);
  }
  flush();
  return out;
}
function fail(file, line, why) { throw new Error(`${path.basename(file)}: ${why}: ${line}`); }

const dir = path.join(HERE, 'script');
const entries = fs.readdirSync(dir).filter((f) => f.endsWith('.txt')).sort().flatMap((f) => parse(path.join(dir, f)));
let durs = {};
try { durs = JSON.parse(fs.readFileSync(path.join(HERE, 'out/durations.json'), 'utf8')); } catch (e) { /* not voiced yet */ }

const utter = new Map();
const rows = entries.map((e) => {
  const s = e.s.map(([sp, text]) => {
    const say = spoken(text), id = SPEAKER[sp] + '_' + crypto.createHash('sha1').update(sp + '|' + say).digest('hex').slice(0, 10);
    if (!utter.has(id)) utter.set(id, { id, speaker: SPEAKER[sp], text: say, caption: text });
    return [sp, text, id, +(durs[id] || 0)];
  });
  return [e.t, e.c, s];
});

const topics = {};
for (const r of rows) topics[r[0]] = (topics[r[0]] || 0) + 1;
const voiced = [...utter.keys()].filter((id) => durs[id] > 0).length;
const js = `// GENERATED by tools/vo/build.mjs from tools/vo/script/*.txt. Do not edit: edit the script and rebuild.
// Each row: [topic, conditions, [[speaker 'M' | 'V', caption, audio id (assets/vo/<id>.mp3), seconds (0: caption only)], ...]].
export const VO_LINES = ${JSON.stringify(rows).replace(/\],\["/g, '],\n["')};
`;
fs.writeFileSync(path.join(ROOT, 'src/wrestling/commentaryLines.js'), js);
fs.mkdirSync(path.join(HERE, 'out'), { recursive: true });
fs.writeFileSync(path.join(HERE, 'out/utterances.json'), JSON.stringify([...utter.values()], null, 1));
const chars = [...utter.values()].reduce((a, u) => a + u.text.length, 0);
console.log(`${rows.length} entries, ${utter.size} utterances (${voiced} voiced), ${chars} characters, ${Object.keys(topics).length} topics`);
if (process.argv.includes('--topics')) console.log(Object.entries(topics).map(([k, n]) => `${k} ${n}`).join(', '));
