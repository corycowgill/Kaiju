// Build KTX2 (Basis UASTC + Zstandard, with mipmaps) copies of the building GLBs into
// assets/ktx2/<same path>, and write src/ktx2Assets.js listing them. Desktop loads these
// through KTX2Loader (GPU-compressed: BC7 on desktop, ~1 byte/texel instead of 4), with the
// JPEG originals as the fallback. Mobile keeps its 512px JPEG copies (assets/m/).
// UASTC for every slot: ETC1S was measured at ~29 dB on building colour maps (visible
// block/chroma smearing on window grids); UASTC is ~40 dB, visually identical.
// usage: node tools/make_ktx2_assets.mjs [name-filter]
//   (needs: npm i @gltf-transform/core @gltf-transform/extensions ktx2-encoder sharp)
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { ktx2 } from 'ktx2-encoder/gltf-transform';
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = process.env.KAIJU_REPO || path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const A = `${REPO}/assets`;
const OUT = `${A}/ktx2`;
const DIRS = ['buildings'];
const filter = process.argv[2] ? new RegExp(process.argv[2]) : null;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const imageDecoder = async (buf) => {
  const { data, info } = await sharp(Buffer.from(buf)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  return { width: info.width, height: info.height, data: new Uint8Array(data.buffer, data.byteOffset, data.byteLength) };
};
const base = { imageDecoder, isUASTC: true, needSupercompression: true, generateMipmap: true };
const done = [];
for (const dir of DIRS) {
  for (const f of fs.readdirSync(`${A}/${dir}`).filter((n) => n.endsWith('.glb')).sort()) {
    const rel = `${dir}/${f}`;
    const out = `${OUT}/${rel}`;
    if (filter && !filter.test(rel)) { if (fs.existsSync(out)) done.push(rel); continue; }
    const t0 = Date.now();
    const doc = await io.read(`${A}/${rel}`);
    await doc.transform(
      ktx2({ ...base, slots: /^(baseColorTexture|emissiveTexture)$/, isPerceptual: true, isSetKTX2SRGBTransferFunc: true }),
      ktx2({ ...base, slots: /^normalTexture$/, isNormalMap: true, isPerceptual: false, isSetKTX2SRGBTransferFunc: false }),
      ktx2({ ...base, slots: /^(metallicRoughnessTexture|occlusionTexture)$/, isPerceptual: false, isSetKTX2SRGBTransferFunc: false }),
    );
    if (doc.getRoot().listTextures().some((t) => t.getMimeType() !== 'image/ktx2')) {
      console.warn(`skip ${rel}: not every texture converted`);
      continue;
    }
    fs.mkdirSync(path.dirname(out), { recursive: true });
    await io.write(out, doc);
    console.log(`${rel}: ${(fs.statSync(`${A}/${rel}`).size / 1e6).toFixed(1)} -> ${(fs.statSync(out).size / 1e6).toFixed(1)} MB in ${((Date.now() - t0) / 1000).toFixed(0)} s`);
    done.push(rel);
  }
}
done.sort();
fs.writeFileSync(`${REPO}/src/ktx2Assets.js`, `// GENERATED by tools/make_ktx2_assets.mjs -- do not edit by hand.
// Asset paths (relative to assets/) with a KTX2 (Basis UASTC) copy under assets/ktx2/.
// assetCache.assetURL() swaps these in on desktop once KTX2Loader is ready.
// Re-run the script after adding or replacing a building GLB.
export const KTX2_VARIANTS = new Set(${JSON.stringify(done, null, 2)});
`);
console.log(`${done.length} KTX2 variants`);
