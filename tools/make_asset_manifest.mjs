// Write src/assetManifest.js: a short content hash for every GLB the game fetches through
// assetCache.cachedFetch (assets/**.glb, including the assets/m/ and assets/ktx2/ copies).
// The IndexedDB cache stores each file with its hash, so changing one file re-downloads
// only that file instead of wiping the whole cache (ASSET_VERSION). Re-run after any GLB
// is added, replaced or regenerated (make_mobile_assets / make_ktx2_assets).
// usage: node tools/make_asset_manifest.mjs   (no dependencies)
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = process.env.KAIJU_REPO || path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true })
  .flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));
const hashes = {};
for (const f of walk(path.join(REPO, 'assets')).filter((f) => f.endsWith('.glb')).sort()) {
  const rel = path.relative(REPO, f).split(path.sep).join('/');
  hashes[rel] = crypto.createHash('sha1').update(fs.readFileSync(f)).digest('hex').slice(0, 10);
}
fs.writeFileSync(path.join(REPO, 'src/assetManifest.js'), `// GENERATED by tools/make_asset_manifest.mjs -- do not edit by hand.
// Content hash per GLB (path relative to the site root). assetCache.cachedFetch stores each
// file in IndexedDB with its hash and re-downloads only files whose hash changed.
export const ASSET_HASHES = ${JSON.stringify(hashes, null, 2)};
`);
console.log(`${Object.keys(hashes).length} GLBs hashed`);
