# Tokyo kit: write manifest_kit.js from the validator's measurements (exact bbox) + the build stats' metadata.
#   node tools/tokyo/design/kit_validate.mjs $KIT_SCRATCH/validate.json && python3 tools/tokyo/design/kit_manifest.py
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
S = os.environ.get('KIT_SCRATCH', '/tmp/tokyo_kit')
val = json.load(open(os.path.join(S, 'validate.json')))
order = ['house', 'zakkyo', 'apartment', 'lowrise', 'midrise', 'warehouse', 'glassslab', 'glasstower']
def meta(f): return json.load(open(os.path.join(S, 'stats', f[:-4] + '.json')))
def bucket(h): return 'low' if h < 35 else 'short' if h < 90 else 'medium' if h <= 200 else 'tall'
L = ["// Tokyo generic kit + debris (design-kit; tools/tokyo/design/kit_*.py, built with Blender 4.5).",
     "// One mesh, one material tokyo_kit_<piece>: a painted 1024 base-colour atlas + an EMISSIVE map on the same UVs",
     "// (lit windows, signs, shopfronts, lanterns, aviation lights; emissive factor [1,1,1], the look layer scales it).",
     "// Metres, base y 0, front = +Z, a material-free LOD1 twin each (same UV set, identical bbox).",
     "// trueM = exported bbox [w, h, d] incl. roof clutter / signs; bucket by true height (low < 35 m, short < 90, medium <= 200, tall).",
     "// A piece's style string starts with its family word (the layout's lot style). Generated by kit_manifest.py.", "",
     "export const TOKYO_GENERIC_GLBS = ["]
rows = []
for st in order:
    for f in sorted(val):
        if not f.startswith('tokyo_' + st + '_'): continue
        m = meta(f); v = val[f]; w, h, d = v['size']
        sh = ", share: %d" % m['share'] if m.get('share', 1) != 1 else ''
        L.append("  { file: '%s', bucket: '%s', style: '%s', trueM: [%s, %s, %s], stone: 0x%06x%s, ready: true }, // %s" % (f, bucket(h), m['style'], w, h, d, m['stone'], sh, m['desc']))
        rows.append((f, bucket(h), m['style'], v))
L += ["];", "", "// Roof prop (placed on flat roofs): { name, file, trueM, ready }"]
if 'tokyo_rooftop_mech.glb' in val:
    v = val['tokyo_rooftop_mech.glb']
    L.append("export const TOKYO_ROOFTOP_MECH = { name: 'tokyo_rooftop_mech', file: 'tokyo_rooftop_mech.glb', trueM: [%s, %s, %s], ready: true }; // %s" % (*v['size'], meta('tokyo_rooftop_mech.glb')['desc']))
L += ["", "// Debris chunks (one material each, metres)", "export const TOKYO_DEBRIS_GLBS = ["]
for f in sorted(val):
    if f.startswith('debris_'): L.append("  '%s', // %s  %s m, %d tris" % (f, meta(f)['desc'], ' x '.join(map(str, val[f]['size'])), val[f]['tris0']))
L += ["];", "", "// Phone variants (assets/m/buildings/tokyo/): none made.", ""]
open(os.path.join(HERE, 'manifest_kit.js'), 'w').write('\n'.join(L))
for f, b, st, v in rows + [(f, '-', '-', val[f]) for f in sorted(val) if not any(f.startswith('tokyo_' + s + '_') for s in order)]:
    print('| %s | %s | %s | %s | %d / %d | %d |' % (f, b, st, ' x '.join(map(str, v['size'])), v['tris0'], v['tris1'], v['kb0']))
