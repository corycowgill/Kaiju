# SF kit: write manifest_kit.js from the validator's measurements (exact bbox) + the build stats' metadata.
#   node tools/sf/design/kit_validate.mjs $KIT_SCRATCH/validate.json && python3 tools/sf/design/kit_manifest.py
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
S = os.environ.get('KIT_SCRATCH', '/tmp/sf_kit')
val = json.load(open(os.path.join(S, 'validate.json')))
order = ['victorian', 'brick', 'warehouse', 'lowrise', 'midrise', 'apartment', 'glassslab', 'glasstower']
def meta(f): return json.load(open(os.path.join(S, 'stats', f[:-4] + '.json')))
def bucket(h): return 'low' if h < 35 else 'short' if h < 90 else 'medium' if h <= 200 else 'tall'
L = ["// San Francisco generic kit + debris (design-kit; tools/sf/design/kit_*.py, built with Blender 4.5).",
     "// One mesh, one material sf_kit_<piece>, one painted 1024 atlas, metres, base y 0, front = +Z, LOD1 twin each.",
     "// trueM = exported bbox [w, h, d] incl. roof clutter; bucket by true height (low < 35 m, short < 90, medium <= 200, tall).",
     "// Generated by kit_manifest.py - paste the arrays into src/levels/sfManifest.js.", "",
     "export const SF_GENERIC_GLBS = ["]
rows = []
for st in order:
    for f in sorted(val):
        if not f.startswith('sf_' + st + '_'): continue
        m = meta(f); v = val[f]; w, h, d = v['size']
        sh = ", share: %d" % m['share'] if m.get('share', 1) != 1 else ''
        L.append("  { file: '%s', bucket: '%s', style: '%s', trueM: [%s, %s, %s], stone: 0x%06x%s, ready: true }, // %s" % (f, bucket(h), m['style'], w, h, d, m['stone'], sh, m['desc']))
        rows.append((f, bucket(h), m['style'], v))
L += ["];", "", "// Roof prop (placed on flat roofs): { name, file, trueM, ready }"]
v = val['sf_rooftop_mech.glb']
L.append("export const SF_ROOFTOP_MECH = { name: 'sf_rooftop_mech', file: 'sf_rooftop_mech.glb', trueM: [%s, %s, %s], ready: true }; // %s" % (*v['size'], meta('sf_rooftop_mech.glb')['desc']))
L += ["", "// Debris chunks (one material each, metres)", "export const SF_DEBRIS_GLBS = ["]
for f in sorted(val):
    if f.startswith('debris_'): L.append("  '%s', // %s  %s m, %d tris" % (f, meta(f)['desc'], ' x '.join(map(str, val[f]['size'])), val[f]['tris0']))
L += ["];", "", "// Phone variants (assets/m/buildings/sf/): none made - no piece needs one badly (largest: sf_brick_e 6.5k tris).", ""]
open(os.path.join(HERE, 'manifest_kit.js'), 'w').write('\n'.join(L))
for f, b, st, v in rows + [(f, '-', '-', val[f]) for f in sorted(val) if not any(f.startswith('sf_' + s + '_') for s in order)]:
    print('| %s | %s | %s | %s | %d / %d | %d |' % (f, b, st, ' x '.join(map(str, v['size'])), v['tris0'], v['tris1'], v['kb0']))
