// Build the phone copies of the GLBs (and the ground JPEGs) into assets/m/<same path>, and
// write src/mobileAssets.js listing the paths that have one.
// The source GLBs are already quantized + meshopt-compressed with WebP textures
// (tools/optimize_assets.mjs), so a phone copy only differs by texture size: the same
// texel-density rule at half the desktop density (phone screens show ~11 px per world unit),
// capped at 512 (1024 for the kaiju and the mech: BossMech is kaiju-sized). A file whose
// textures are already within that gets no copy (served as-is); stale copies are removed.
// usage: node tools/make_mobile_assets.mjs   (needs: npm install)
import { Logger } from '@gltf-transform/core';
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeIO, optimizeTextures, compressGeometry } from './lib/glb_opt.mjs';

const REPO = process.env.KAIJU_REPO || path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const A = `${REPO}/assets`;
const OUT = `${A}/m`;
const io = makeIO();
// Hand-authored phone models (an artist's lighter mesh, not just smaller
// textures) live in assets/m/ already: never regenerate them, only list them
// (tools/optimize_assets.mjs compresses them in place)
const PINNED = new Set([
  'buildings/chicago/soldier_field.glb',      // = artist's soldier_field_mobile.glb (9.8k tris)
  'buildings/chicago/soldier_field_lod1.glb', // its matching LOD1
]);
const PHONE = { texelsPerUnit: 10, floor: 128, heroCap: 1024 };
const capFor = (rel) => (/^enemies\/mech\//.test(rel) ? 1024 : 512);

function walk(dir, rel = '') {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const r = rel ? `${rel}/${e.name}` : e.name;
    if (e.isDirectory()) { if (r !== 'm' && r !== 'ktx2') out.push(...walk(`${dir}/${e.name}`, r)); }
    else out.push(r);
  }
  return out;
}

const variants = [];
let before = 0, after = 0;
for (const rel of walk(A).filter((r) => r.endsWith('.glb')).sort()) {
  if (PINNED.has(rel)) {
    if (fs.existsSync(`${OUT}/${rel}`)) variants.push(rel);
    continue;
  }
  const doc = await io.read(`${A}/${rel}`);
  doc.setLogger(new Logger(Logger.Verbosity.WARN));
  const log = await optimizeTextures(doc, rel, { ...PHONE, cap: capFor(rel) });
  const out = `${OUT}/${rel}`;
  if (!log.some((l) => / -> \d+x\d+ .*\((density|cap|constant)/.test(l))) { fs.rmSync(out, { force: true }); continue; } // nothing resized: serve the original
  await compressGeometry(doc, rel);
  const bin = await io.writeBinary(doc);
  const src = fs.statSync(`${A}/${rel}`).size;
  if (bin.byteLength >= src) { fs.rmSync(out, { force: true }); continue; }
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, bin);
  before += src; after += bin.byteLength;
  variants.push(rel);
}
// Ground tile textures (loaded by TextureLoader in city.js)
for (const rel of walk(`${A}/textures`, 'textures').filter((r) => r.endsWith('.jpg'))) {
  const src = `${A}/${rel}`;
  const meta = await sharp(src).metadata();
  if (Math.max(meta.width, meta.height) <= 512) continue;
  fs.mkdirSync(path.dirname(`${OUT}/${rel}`), { recursive: true });
  await sharp(src).resize(512, 512, { fit: 'inside', kernel: 'lanczos3' })
    .jpeg({ quality: 88, chromaSubsampling: '4:4:4', mozjpeg: true }).toFile(`${OUT}/${rel}`);
  before += fs.statSync(src).size; after += fs.statSync(`${OUT}/${rel}`).size;
  variants.push(rel);
}
// Copies of files that no longer exist in the source tree
const keep = new Set(variants);
for (const rel of walk(OUT)) if (!keep.has(rel)) fs.rmSync(`${OUT}/${rel}`);
variants.sort();
fs.writeFileSync(`${REPO}/src/mobileAssets.js`, `// GENERATED by tools/make_mobile_assets.mjs -- do not edit by hand.
// Asset paths (relative to assets/) that have a reduced-texture mobile variant
// under assets/m/ (512px textures at most; 1024px for the kaiju and mech).
// assetCache.assetURL() swaps these in on mobile. Re-run the script after
// adding or replacing a GLB or ground texture.
export const MOBILE_VARIANTS = new Set(${JSON.stringify(variants, null, 2)});
`);
console.log(`${variants.length} variants, ${(before / 1e6).toFixed(1)} MB -> ${(after / 1e6).toFixed(1)} MB`);
